export function formatDH(amount: number, showDecimals = false): string {
  const formatted = new Intl.NumberFormat('fr-FR', {
    minimumFractionDigits: showDecimals ? 2 : 0,
    maximumFractionDigits: showDecimals ? 2 : 0,
  }).format(amount);
  return `${formatted} DH`;
}

